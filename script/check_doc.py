#!/usr/bin/env python3
"""Documentation check: note front matter and index, note references, and Markdown links."""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
NOTE_DIR = ROOT / "note"
INDEX = NOTE_DIR / "README.md"
INDEX_MARKER = "<!-- generated by script/check_doc.py; do not edit below -->"
MARKDOWN = ("README.md", "CONTRIBUTING.md", "CLAUDE.md", "doc/**/*.md", "note/**/*.md", "spec/*.md")

KIND = ("rule", "fact", "procedure", "rationale")
KEY = {"id", "title", "kind", "path", "related"}
ID_RE = re.compile(r"^([A-Z]+)-(\d{3})$")
TITLE_LIMIT = 80
FENCE_RE = re.compile(r"^(```|~~~).*?^\1\s*$", re.MULTILINE | re.DOTALL)
CODE_RE = re.compile(r"`[^`\n]*`")
LINK_RE = re.compile(r"\]\(([^)\s]+)\)")
HEADING_RE = re.compile(r"^#{1,6}\s+(.+?)\s*#*\s*$", re.MULTILINE)
EXTERNAL = ("http://", "https://", "mailto:")


@dataclass
class Note:
    id: str
    topic: str
    title: str
    kind: str
    path: list[str]
    related: list[str]
    file: Path


def parse_front_matter(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise ValueError(f"{path}: missing YAML front matter")
    end = text.find("\n---\n", 4)
    if end < 0:
        raise ValueError(f"{path}: unterminated YAML front matter")
    data = yaml.safe_load(text[4:end])
    if not isinstance(data, dict):
        raise ValueError(f"{path}: front matter is not a mapping")
    if not text[end + 5 :].strip():
        raise ValueError(f"{path}: empty body")
    return data


def string_list(value, path: Path, key: str, errors: list[str]) -> list[str]:
    if value is None:
        return []
    if not isinstance(value, list) or not all(isinstance(v, str) and v for v in value):
        errors.append(f"{path}: '{key}' must be a list of non-empty strings")
        return []
    return value


def load_note(errors: list[str]) -> list[Note]:
    notes: list[Note] = []
    for file in sorted(NOTE_DIR.glob("*/*.md")):
        rel = file.relative_to(ROOT)
        try:
            data = parse_front_matter(file)
        except ValueError as exc:
            errors.append(str(exc))
            continue
        if unknown := sorted(set(data) - KEY):
            errors.append(f"{rel}: unknown key {', '.join(unknown)}")
        nid = str(data.get("id", ""))
        match = ID_RE.match(nid)
        if not match:
            errors.append(f"{rel}: bad id '{nid}' (PREFIX-NNN)")
            continue
        if nid != file.stem:
            errors.append(f"{rel}: id '{nid}' must equal the file stem '{file.stem}'")
        topic = file.parent.name
        if match[1] != topic.upper():
            errors.append(f"{rel}: id prefix must be '{topic.upper()}' in note/{topic}/")
        title = data.get("title")
        if not isinstance(title, str) or not title or "|" in title:
            errors.append(f"{rel}: 'title' must be a non-empty string without '|'")
            title = ""
        elif len(title) > TITLE_LIMIT:
            errors.append(f"{rel}: title longer than {TITLE_LIMIT} characters")
        kind = data.get("kind")
        if kind not in KIND:
            errors.append(f"{rel}: 'kind' must be one of {', '.join(KIND)}")
        paths = string_list(data.get("path"), rel, "path", errors)
        for pattern in paths:
            if pattern.startswith("/") or ".." in Path(pattern).parts:
                errors.append(f"{rel}: path '{pattern}' must be relative to the repository root")
            elif not any(ROOT.glob(pattern)):
                errors.append(f"{rel}: path '{pattern}' matches no file")
        related = string_list(data.get("related"), rel, "related", errors)
        notes.append(Note(nid, topic, title, str(kind), paths, related, file))
    return notes


def check_reference(notes: list[Note], errors: list[str]) -> None:
    known = {note.id for note in notes}
    for note in notes:
        for other in note.related:
            if other not in known:
                errors.append(f"{note.file.relative_to(ROOT)}: related '{other}' does not exist")
            elif other == note.id:
                errors.append(f"{note.file.relative_to(ROOT)}: related lists the note itself")
    topics = {note.topic.upper() for note in notes}
    if not topics:
        return
    ref_re = re.compile(r"\b(?:" + "|".join(sorted(topics)) + r")-\d{3}\b")
    for file in markdown_file():
        for ref in ref_re.findall(file.read_text(encoding="utf-8")):
            if ref not in known:
                errors.append(f"{file.relative_to(ROOT)}: note '{ref}' does not exist")


def render_index(notes: list[Note]) -> str:
    lines = [INDEX_MARKER, "", "## By topic"]
    for topic in sorted({note.topic for note in notes}):
        lines += ["", f"### {topic}", "", "| ID | Kind | Title |", "|---|---|---|"]
        for note in notes:
            if note.topic == topic:
                lines.append(f"| [{note.id}]({topic}/{note.id}.md) | {note.kind} | {note.title} |")
    by_path: dict[str, list[str]] = {}
    for note in notes:
        for pattern in note.path:
            by_path.setdefault(pattern, []).append(note.id)
    lines += ["", "## By path", "", "| Path | Note |", "|---|---|"]
    for pattern in sorted(by_path):
        lines.append(f"| `{pattern}` | {', '.join(by_path[pattern])} |")
    return "\n".join(lines) + "\n"


def check_index(notes: list[Note], write: bool, errors: list[str]) -> None:
    if not INDEX.is_file():
        errors.append(f"{INDEX.relative_to(ROOT)} does not exist")
        return
    text = INDEX.read_text(encoding="utf-8")
    head, marker, _ = text.partition(INDEX_MARKER)
    if not marker:
        errors.append(f"{INDEX.relative_to(ROOT)}: missing marker '{INDEX_MARKER}'")
        return
    for topic in sorted({note.topic for note in notes}):
        if f"`{topic}/`" not in head:
            errors.append(f"{INDEX.relative_to(ROOT)}: topic `{topic}/` is not described")
    expected = head + render_index(notes)
    if text == expected:
        return
    if write:
        INDEX.write_text(expected, encoding="utf-8")
    else:
        errors.append(f"{INDEX.relative_to(ROOT)}: index is stale; run script/check_doc.py --write")


def markdown_file() -> list[Path]:
    found: set[Path] = set()
    for pattern in MARKDOWN:
        found.update(path for path in ROOT.glob(pattern) if path.is_file())
    return sorted(found)


def anchor(heading: str) -> str:
    text = CODE_RE.sub(lambda m: m[0].strip("`"), heading).lower()
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"[^\w\- ]", "", text).replace(" ", "-")
    return re.sub(r"-{2,}", "-", text)


def anchor_set(path: Path) -> set[str]:
    text = FENCE_RE.sub("", path.read_text(encoding="utf-8"))
    found: set[str] = set()
    for heading in HEADING_RE.findall(text):
        base = anchor(heading)
        name, n = base, 0
        while name in found:
            n += 1
            name = f"{base}-{n}"
        found.add(name)
    return found


def check_link(errors: list[str]) -> None:
    for file in markdown_file():
        text = CODE_RE.sub("", FENCE_RE.sub("", file.read_text(encoding="utf-8")))
        for target in LINK_RE.findall(text):
            if target.startswith(EXTERNAL):
                continue
            ref, _, fragment = target.partition("#")
            dest = (file.parent / ref).resolve() if ref else file
            rel = file.relative_to(ROOT)
            if not dest.exists():
                errors.append(f"{rel}: link '{target}' points to a missing file")
            elif fragment and dest.suffix == ".md" and fragment not in anchor_set(dest):
                errors.append(f"{rel}: link '{target}' points to a missing heading")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--write", action="store_true", help="rewrite the generated note index")
    args = ap.parse_args()

    errors: list[str] = []
    notes = load_note(errors)
    check_reference(notes, errors)
    check_index(notes, args.write, errors)
    check_link(errors)
    for e in errors:
        print(f"error: {e}", file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
