#!/usr/bin/env python3
"""Spec gate: validate spec/<method>.md, generate prover check files, and emit the report."""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC_DIR = ROOT / "spec"
LEAN_DIR = ROOT / "verification" / "lean"
ROCQ_DIR = ROOT / "verification" / "rocq"
REPORT = ROOT / "doc" / "verification.md"
REPORT_MARKER = "<!-- generated by script/check_spec.py; do not edit below -->"
FRAMA_C_EXPECTATION = ROOT / "verification" / "frama-c" / "expectation.txt"
ALLOW_FILE = ROOT / "script" / "axiom_allow.yaml"

ID_RE = re.compile(r"^[A-Z]{2,}-[ABC]\d+$")
PROVERS = ("lean", "rocq")
LAYER_REQUIRE = {"A": ("lean", "rocq"), "B": ("rocq",), "C": ()}


@dataclass
class Theorem:
    spec: str
    id: str
    layer: str
    informal: str
    lean: str | None = None
    rocq: str | None = None
    acsl: str | None = None
    result: dict[str, str] = field(default_factory=dict)


def parse_front_matter(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise ValueError(f"{path}: missing YAML front matter")
    end = text.find("\n---\n", 4)
    if end < 0:
        raise ValueError(f"{path}: unterminated YAML front matter")
    data = yaml.safe_load(text[4:end])
    if not isinstance(data, dict):
        raise ValueError(f"{path}: front matter is not a mapping")
    return data


def load_spec(errors: list[str]) -> list[Theorem]:
    theorems: list[Theorem] = []
    seen: set[str] = set()
    for path in sorted(SPEC_DIR.glob("*.md")):
        try:
            data = parse_front_matter(path)
        except ValueError as exc:
            errors.append(str(exc))
            continue
        name = path.stem
        if data.get("method") != name:
            errors.append(f"{path}: method '{data.get('method')}' must equal file stem '{name}'")
        kernel = data.get("kernel")
        if not kernel or not (ROOT / kernel).is_file():
            errors.append(f"{path}: kernel '{kernel}' does not exist")
        for entry in data.get("theorem") or []:
            tid = str(entry.get("id", ""))
            if not ID_RE.match(tid):
                errors.append(f"{path}: bad theorem id '{tid}'")
                continue
            if tid in seen:
                errors.append(f"{path}: duplicate theorem id '{tid}'")
            seen.add(tid)
            if tid.split("-")[0] != name.upper():
                errors.append(f"{path}: {tid}: id prefix must be '{name.upper()}'")
            layer = str(entry.get("layer", ""))
            if layer not in LAYER_REQUIRE:
                errors.append(f"{path}: {tid}: layer must be A, B, or C")
                continue
            if layer != tid.split("-")[1][0]:
                errors.append(f"{path}: {tid}: id letter does not match layer {layer}")
            if not entry.get("informal"):
                errors.append(f"{path}: {tid}: missing informal statement")
            for prover in LAYER_REQUIRE[layer]:
                if not entry.get(prover):
                    errors.append(f"{path}: {tid}: layer {layer} requires a '{prover}' name")
            if layer == "C" and not (entry.get("rocq") or entry.get("acsl")):
                errors.append(f"{path}: {tid}: layer C requires 'rocq' (VST) or 'acsl'")
            acsl = entry.get("acsl")
            if acsl:
                file, _, func = str(acsl).partition(":")
                target = ROOT / file
                if not target.is_file():
                    errors.append(f"{path}: {tid}: acsl file '{file}' does not exist")
                elif func and not re.search(rf"\b{re.escape(func)}\s*\(", target.read_text()):
                    errors.append(f"{path}: {tid}: function '{func}' not found in {file}")
            theorems.append(
                Theorem(
                    spec=name,
                    id=tid,
                    layer=layer,
                    informal=str(entry.get("informal", "")).strip(),
                    lean=entry.get("lean"),
                    rocq=entry.get("rocq"),
                    acsl=acsl,
                )
            )
    return theorems


DECL_RE = {
    "lean": r"^\s*(?:@\[[^\]]*\]\s*)?(?:private\s+|protected\s+|noncomputable\s+)*"
    r"(?:theorem|lemma|def|abbrev|instance)\s+{name}\b",
    "rocq": r"^\s*(?:Theorem|Lemma|Corollary|Proposition|Definition|Fixpoint|Instance)\s+{name}\b",
}


def constant_declared(prover: str, name: str) -> bool:
    parts = name.split(".")
    if prover == "lean":
        module = (LEAN_DIR / Path(*parts[:-1])).with_suffix(".lean")
    else:
        module = (ROCQ_DIR / "theory" / Path(*parts[1:-1])).with_suffix(".v")
    if not module.is_file():
        return False
    pattern = DECL_RE[prover].format(name=re.escape(parts[-1]))
    return re.search(pattern, module.read_text(encoding="utf-8"), re.MULTILINE) is not None


def write_check_file(theorems: list[Theorem]) -> None:
    lean: list[str] = []
    rocq: list[str] = []
    for t in theorems:
        if t.lean:
            if constant_declared("lean", t.lean):
                lean.append(t.lean)
            else:
                t.result["lean"] = "missing"
        if t.rocq:
            if constant_declared("rocq", t.rocq):
                rocq.append(t.rocq)
            else:
                t.result["rocq"] = "missing"
    if LEAN_DIR.is_dir():
        lines = ["-- generated by script/check_spec.py; do not edit", "import Diana", ""]
        lines += [f"#print axioms {n}" for n in lean]
        (LEAN_DIR / "CheckSpec.lean").write_text("\n".join(lines) + "\n")
    if ROCQ_DIR.is_dir():
        lines = ["(* generated by script/check_spec.py; do not edit *)"]
        mods = sorted({n.rsplit(".", 1)[0] for n in rocq})
        lines += [f"From {m.rsplit('.', 1)[0]} Require Import {m.rsplit('.', 1)[1]}." for m in mods]
        lines += [f"Print Assumptions {n}." for n in rocq]
        (ROCQ_DIR / "CheckSpec.v").write_text("\n".join(lines) + "\n")


AXIOM_LINE_RE = re.compile(r"^([^\s:]+)(?:[ \t]+:.*)?[ \t]*$")

LEAN_AXIOM_RE = re.compile(
    r"'([^']+)' depends on axioms: \[([^\]]*)\]|'([^']+)' does not depend on any axioms"
)


def run_prover(
    theorems: list[Theorem], allow: dict[str, list[str]], provers: tuple[str, ...]
) -> None:
    for prover, directory, cmd in (
        ("lean", LEAN_DIR, ["lake", "env", "lean", "CheckSpec.lean"]),
        ("rocq", ROCQ_DIR, ["make", "-s", "check"]),
    ):
        if prover not in provers:
            continue
        pending = [t for t in theorems if getattr(t, prover) and prover not in t.result]
        names = [getattr(t, prover) for t in pending]
        by_name = {getattr(t, prover): t for t in pending}
        if not names:
            continue
        if not directory.is_dir():
            for t in by_name.values():
                t.result[prover] = "no project"
            continue
        try:
            proc = subprocess.run(cmd, cwd=directory, capture_output=True, text=True)
        except FileNotFoundError as exc:
            for t in by_name.values():
                t.result[prover] = "check failed"
            print(f"error: {prover}: cannot run {cmd[0]!r}: {exc.strerror}", file=sys.stderr)
            continue
        out = proc.stdout + proc.stderr
        if proc.returncode != 0:
            for t in by_name.values():
                t.result[prover] = "check failed"
            sys.stderr.write(out)
            continue
        try:
            found = (
                parse_lean_axiom(out) if prover == "lean" else parse_rocq_axiom(proc.stdout, names)
            )
        except ValueError as exc:
            for t in by_name.values():
                t.result[prover] = "check failed"
            print(f"error: {prover}: invalid assumption output: {exc}", file=sys.stderr)
            continue
        for name, t in by_name.items():
            if name not in found:
                t.result[prover] = "missing"
                continue
            bad = sorted(set(found[name]) - set(allow.get(prover, [])))
            t.result[prover] = "ok" if not bad else "axiom: " + ", ".join(bad)


def parse_lean_axiom(out: str) -> dict[str, list[str]]:
    found: dict[str, list[str]] = {}
    for m in LEAN_AXIOM_RE.finditer(out):
        if m.group(3):
            found[m.group(3)] = []
        else:
            found[m.group(1)] = [a.strip() for a in m.group(2).split(",") if a.strip()]
    return found


def parse_rocq_axiom(out: str, names: list[str]) -> dict[str, list[str]]:
    """Map each name to the axioms of its `Print Assumptions` block, matched by position.

    Rocq does not echo the constant name, so a missing or extra block would shift every
    later name onto the wrong axiom set; the count is checked instead of truncated.
    Raise ValueError on any output this cannot account for.
    """
    blocks = re.split(r"(?m)^(?=Closed under the global context|Axioms:)", out)
    blocks = [b for b in blocks if b.startswith(("Closed under", "Axioms:"))]
    if len(blocks) != len(names):
        raise ValueError(f"expected {len(names)} assumption block(s), got {len(blocks)}")
    found: dict[str, list[str]] = {}
    for name, block in zip(names, blocks, strict=True):
        line = block.splitlines()
        if line[0].rstrip() == "Closed under the global context":
            if any(rest.strip() for rest in line[1:]):
                raise ValueError(f"{name}: unexpected output after a closed-context report")
            found[name] = []
            continue
        axiom = []
        for rest in line[1:]:
            if not rest.strip() or rest[0].isspace():
                continue
            m = AXIOM_LINE_RE.fullmatch(rest)
            if m is None:
                raise ValueError(f"{name}: unrecognized axiom line {rest!r}")
            axiom.append(m.group(1))
        if not axiom:
            raise ValueError(f"{name}: empty axiom block")
        found[name] = axiom
    return found


def acsl_file(t: Theorem) -> str:
    return str(t.acsl).partition(":")[0]


def frama_c_status(source: str) -> str:
    if not FRAMA_C_EXPECTATION.is_file():
        return "planned"
    rows = []
    for line in FRAMA_C_EXPECTATION.read_text().splitlines():
        fields = line.split()
        if fields and fields[0] == source:
            rows.append(fields)
    if not rows:
        return "planned"
    if len(rows) != 1 or len(rows[0]) != 2 or not re.fullmatch(r"[1-9][0-9]*", rows[0][1]):
        return "unreadable"
    total = rows[0][1]
    return f"ok ({total}/{total})"


def write_report(theorems: list[Theorem]) -> None:
    head, marker, _ = REPORT.read_text(encoding="utf-8").partition(REPORT_MARKER)
    if not marker:
        raise ValueError(f"{REPORT}: missing marker line {REPORT_MARKER!r}")
    lines = [
        "| Spec | ID | Layer | Lean | Rocq | Frama-C | Statement |",
        "|---|---|---|---|---|---|---|",
    ]
    for t in theorems:
        cells = []
        for prover in ("lean", "rocq"):
            name = getattr(t, prover)
            if not name:
                cells.append("–")
            else:
                cells.append(t.result.get(prover, "planned").replace("no project", "planned"))
        cells.append(frama_c_status(acsl_file(t)) if t.acsl else "–")
        informal = t.informal.replace("|", "\\|")
        lines.append(
            f"| {t.spec} | {t.id} | {t.layer} | {cells[0]} | {cells[1]} | {cells[2]} | {informal} |"
        )
    REPORT.write_text(head + marker + "\n\n" + "\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--run", action="store_true", help="run the provers on the check files")
    ap.add_argument(
        "--prover",
        action="append",
        choices=PROVERS,
        help="prover to check with --run and --strict (repeatable; default: all)",
    )
    ap.add_argument("--strict", action="store_true", help="fail unless every theorem is verified")
    ap.add_argument("--no-report", action="store_true", help="do not rewrite the report")
    args = ap.parse_args()

    errors: list[str] = []
    theorems = load_spec(errors)
    if errors:
        for e in errors:
            print(f"error: {e}", file=sys.stderr)
        return 1
    if not theorems:
        print("error: no theorem found under spec/", file=sys.stderr)
        return 1

    write_check_file(theorems)
    allow = yaml.safe_load(ALLOW_FILE.read_text()) if ALLOW_FILE.is_file() else {}
    provers = tuple(args.prover) if args.prover else PROVERS
    if args.run:
        run_prover(theorems, allow, provers)
    if not args.no_report:
        try:
            write_report(theorems)
        except ValueError as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 1

    unverified = [
        (t.id, p, t.result.get(p, "not run"))
        for t in theorems
        for p in provers
        if getattr(t, p) and t.result.get(p) != "ok"
    ]
    if args.strict and not args.prover:
        for t in theorems:
            if not t.acsl:
                continue
            source = acsl_file(t)
            status = frama_c_status(source)
            if status == "planned":
                unverified.append((t.id, "frama-c", f"missing expectation for {source}"))
            elif status == "unreadable":
                unverified.append((t.id, "frama-c", f"invalid expectation for {source}"))
    print(f"{len(theorems)} theorem(s) in {len({t.spec for t in theorems})} spec file(s)")
    for tid, p, why in unverified:
        print(f"  {tid} [{p}]: {why}")
    if args.strict and unverified:
        return 1
    if any(why == "check failed" or why.startswith("axiom:") for _, _, why in unverified):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
